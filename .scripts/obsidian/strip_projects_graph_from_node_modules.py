#!/usr/bin/env python3
"""Remove batch_projects_graph_metadata output from markdown under node_modules (04-Projects)."""

from __future__ import annotations

import re
import sys
from pathlib import Path

FRONTMATTER_RE = re.compile(r"^---\s*\r?\n(?P<body>.*?)\r?\n---\s*\r?\n", re.DOTALL)
GRAPH_LINE_RE = re.compile(r"^Graph links:.*\r?\n?", re.MULTILINE)


def strip_one(text: str) -> str | None:
    m = FRONTMATTER_RE.match(text)
    if not m:
        return None
    body_fm = m.group("body")
    if "domain: projects" not in body_fm or "04-Projects/_MOC_Projects" not in body_fm:
        return None
    rest = text[m.end() :]
    rest = GRAPH_LINE_RE.sub("", rest).lstrip("\n")
    return rest


def main() -> int:
    root = Path(__file__).resolve().parents[2]
    projects = root / "04-Projects"
    if not projects.is_dir():
        return 2
    changed = 0
    for path in projects.rglob("*.md"):
        if "node_modules" not in path.as_posix():
            continue
        try:
            raw = path.read_text(encoding="utf-8")
        except OSError:
            continue
        new = strip_one(raw)
        if new is None or new == raw:
            continue
        path.write_text(new, encoding="utf-8", newline="\n")
        changed += 1
    print(f"stripped_files={changed}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
